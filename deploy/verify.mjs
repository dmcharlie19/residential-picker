import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const {chromium}=createRequire(new URL('../frontend/package.json',import.meta.url))('@playwright/test');
const target=new URL(process.env.SERVER_URL||'https://vibrationpanel.ru/residential/');
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE_PATH?{executablePath:process.env.BROWSER_EXECUTABLE_PATH}:{}),args:process.env.SERVER_HOST_ADDRESS?[`--host-resolver-rules=MAP ${target.hostname} ${process.env.SERVER_HOST_ADDRESS}`]:[]});
const evidence=new URL('../docs/evidence/',import.meta.url);
await mkdir(evidence,{recursive:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
const assets=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(new URL(r.url()).pathname.includes('/assets/'))assets.push(new URL(r.url()).pathname)});
try {
 await page.goto(target.href);
 await page.getByRole('heading',{level:1}).waitFor();
 assert.equal(await page.getByRole('link',{name:'Квадрат — главная'}).getAttribute('href'),'/residential/');
 await page.getByRole('button',{name:'Подобрать'}).click();
 await page.getByRole('heading',{name:/Подходящие варианты/}).waitFor();
 const data=await page.evaluate(async()=>{const response=await fetch(new URL('api/v1/search?city='+encodeURIComponent('Сочи')+'&budget=20000000&rooms=1&rooms=2',location.href));if(!response.ok)throw new Error('API status '+response.status);return response.json()});
 assert(data.count>3);
 assert.equal(await page.locator('article').count(),data.count);
 const prices=data.results.map(x=>BigInt(x.estimated_price_rub.replace('.','')));
 assert(prices.every((x,i)=>i===0||prices[i-1]<=x));
 assert(data.results.every(x=>[1,2].includes(x.lot.rooms)));
 assert(assets.length>0 && assets.every(p=>p.startsWith('/residential/assets/')));
 await page.screenshot({path:fileURLToPath(new URL('server-room-search.png',evidence)),fullPage:true});
 await page.setViewportSize({width:360,height:800});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:fileURLToPath(new URL('server-room-search-mobile.png',evidence)),fullPage:true});
 await page.getByLabel('Бюджет, ₽').fill('1');
 await page.getByRole('button',{name:'Подобрать'}).click();
 await page.getByRole('heading',{name:'Подходящих вариантов пока нет'}).waitFor();
 assert.deepEqual(errors,[]);
 const report={url:target.href,hostOverride:process.env.SERVER_HOST_ADDRESS||null,count:data.count,rooms:data.query.rooms,assets,checks:['TLS page','base path assets','base path API','brand link','room filter','ascending prices','unlimited results','mobile layout','empty result'],pageErrors:errors};
 await writeFile(new URL('server-verification.json',evidence),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));
}finally{await browser.close()}
